export type LangCode = keyof typeof dictionaries;
export type CopyKey = keyof typeof dictionaries.en;
export const categoryKeys = ["men", "women", "kids", "fragrance", "accessories"] as const;
export type CategoryKey = (typeof categoryKeys)[number];

export function isCategoryKey(value: string): value is CategoryKey {
  return (categoryKeys as readonly string[]).includes(value);
}

export function isCopyKey(value: string): value is CopyKey {
  return value in dictionaries.en;
}

export function isRtlLang(lang: string) {
  return lang === "fa-AF" || lang === "ps";
}

export function translate(lang: string, key: CopyKey) {
  const dict = dictionaries[lang as LangCode] ?? dictionaries.en;
  return dict[key] ?? dictionaries.en[key];
}

